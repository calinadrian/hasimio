// Regenerates shared/romanian-series.mjs. Run before a release: npm run catalog:romanian
// IMDb's datasets have no country of origin, and a Romanian title on its own only says a show was
// released there. So those titles only nominate candidates; Cinemeta's country field confirms them.
// TVmaze networks based in Romania add the shows Cinemeta has no country for.
import {writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {datasetRows} from '../server/title-index.mjs';

const output=path.join(path.dirname(fileURLToPath(import.meta.url)),'..','shared','romanian-series.mjs');
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));

async function tvmazeRomanian() {
  const ids=new Set();
  for (let page=0;;page++) {
    const response=await fetch(`https://api.tvmaze.com/shows?page=${page}`);
    if (response.status === 404) return ids;
    if (response.status === 429) { await wait(5000);page--;continue; }
    if (!response.ok) throw new Error(`TVmaze returned HTTP ${response.status}.`);
    for (const show of await response.json()) {
      const country=show.network?.country?.code ?? show.webChannel?.country?.code;
      if ((country === 'RO' || show.language === 'Romanian') && /^tt\d+$/.test(show.externals?.imdb ?? '')) ids.add(show.externals.imdb);
    }
    await wait(550);
  }
}
async function cinemetaCountries(ids) {
  const countries=new Map(),queue=[...ids];
  await Promise.all(Array.from({length:6},async()=>{
    for (let id=queue.pop();id;id=queue.pop()) {
      const response=await fetch(`https://v3-cinemeta.strem.io/meta/series/${id}.json`,{signal:AbortSignal.timeout(20000)}).catch(()=>undefined);
      if (response?.ok) countries.set(id,(await response.json()).meta?.country);
    }
  }));
  return countries;
}

console.log('Reading IMDb datasets…');
const votes=new Map();
for await (const [id,,count] of datasetRows('title.ratings.tsv.gz',fetch)) votes.set(id,Number(count));
const series=new Map();
for await (const [id,kind,primary,original,adult,start] of datasetRows('title.basics.tsv.gz',fetch))
  if ((kind === 'tvSeries' || kind === 'tvMiniSeries') && adult !== '1') series.set(id,{id,name:original === '\\N' ? primary : original,year:Number(start) || undefined,votes:votes.get(id) ?? 0});
const candidates=new Set();
for await (const [id,,,region] of datasetRows('title.akas.tsv.gz',fetch)) if (region === 'RO' && series.has(id)) candidates.add(id);
console.log(`${candidates.size} series have a Romanian title. Reading TVmaze…`);
const tvmaze=await tvmazeRomanian();
for (const id of tvmaze) if (series.has(id)) candidates.add(id);
console.log(`${tvmaze.size} Romanian shows on TVmaze. Confirming ${candidates.size} candidates with Cinemeta…`);
const countries=await cinemetaCountries(candidates);
if (countries.size < candidates.size*.8) throw new Error(`Cinemeta only answered for ${countries.size} of ${candidates.size} candidates; keeping the current list.`);
// The first country is where the show is from. Later ones are co-producers, as with Germany, Romania.
const confirmed=[...candidates].filter(id=>tvmaze.has(id) || /^romania\b/i.test(countries.get(id) ?? ''))
  .map(id=>series.get(id)).sort((a,b)=>b.votes-a.votes || (b.year ?? 0)-(a.year ?? 0) || a.id.localeCompare(b.id));
const lines=confirmed.map(({id,name,year})=>`  ${JSON.stringify({id,name,...(year ? {year} : {})})},`);
await writeFile(output,`// Generated by scripts/build-romanian-series.mjs. Do not edit by hand. Most rated first.
export const romanianSeries=[
${lines.join('\n')}
];
export const romanianSeriesIds=new Set(romanianSeries.map(show=>show.id));
// Metahub artwork works for any IMDb ID, which also covers shows TVmaze has not linked to IMDb.
export function romanianCatalog(skip=0,size=50) {
  const page=romanianSeries.slice(skip,skip+size);
  return {metas:page.map(({id,name,year})=>({id,type:'series',name,releaseInfo:year ? String(year) : undefined,poster:\`https://images.metahub.space/poster/medium/\${id}/img\`})),hasMore:skip+size<romanianSeries.length};
}
`);
console.log(`Wrote ${confirmed.length} Romanian series.`);
